export function createLevel(id = 1) {
  const n = Math.max(1, Math.min(TOTAL_LEVELS, id | 0));
  const def = DEFS.find((d) => d.id === n) || DEFS[0];
  return make(def);
}

export function createLevel1() {
  return createLevel(1);
}
